export const getOrderById = (orderId) => {
  const norm = orderId?.replace('#', '').toUpperCase();
  const direct = PRIMARY_ORDERS.find(
    (o) => o.id.toUpperCase() === norm || o.orderId.toUpperCase() === `#${norm}`
  );
  if (direct) return direct;

  // Search across generated orders
  for (const v of VENDOR_ORDERS_SUMMARY) {
    const list = getOrdersByVendorId(v.vendorId);
    const found = list.find((o) => o.id.toUpperCase() === norm || o.orderId.toUpperCase() === `#${norm}`);
    if (found) return found;
  }

  return PRIMARY_ORDERS[0];
};

export const getVendorSummaryById = (vendorId) => {
  const norm = vendorId?.replace('#', '').toUpperCase();
  return (
    VENDOR_ORDERS_SUMMARY.find(
      (v) => v.vendorId.toUpperCase() === norm || v.vendorId.toUpperCase() === `VDR-${norm}`
    ) || VENDOR_ORDERS_SUMMARY[0]
  );
};
